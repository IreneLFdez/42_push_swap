#include "libft.h"

char	*ft_strmapi(const char *s, char (*f)(unsigned int, char))
{
	int		i;
	char	*mapi;

	i = 0;
	if (!s || !f)
		return (NULL);
	mapi = (char *) malloc ((ft_strlen(s) + 1) * sizeof(char));
	if (mapi == NULL)
		return (NULL);
	while (s[i])
	{
		mapi[i] = f(i, s[i]);
		i++;
	}
	mapi[i] = '\0';
	return (mapi);
}
