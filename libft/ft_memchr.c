#include "libft.h"

void	*ft_memchr(const void *s, int c, size_t n)
{
	size_t			i;
	unsigned char	*pointer;

	i = 0;
	pointer = (unsigned char *)s;
	while (i < n)
	{
		if (pointer[i] == (unsigned char)c)
			return ((void *)&pointer[i]);
		i++;
	}
	return (NULL);
}
